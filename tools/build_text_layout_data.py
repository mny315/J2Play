#!/usr/bin/env python3
"""Generate BMP bitmap text properties from pinned Unicode 17.0.0 data."""

import argparse
import hashlib
from pathlib import Path


SOURCES = {
    "BidiMirroring.txt": "a2f16fb873ab4fcdf3221cb1a8a85a134ddd6ed03603181823ff5206af3741ce",
    "ArabicShaping.txt": "39afa01e680e27d0fd10b67a9b27be13fbaa3d0efecfb5be45991de9a0d267d0",
    "UnicodeData.txt": "2e1efc1dcb59c575eedf5ccae60f95229f706ee6d031835247d843c11d96470c",
}


def read_verified(path, name):
    data = path.read_bytes()
    if hashlib.sha256(data).hexdigest() != SOURCES[name]:
        raise ValueError(f"unexpected Unicode 17 source sha256: {name}")
    return data.decode("utf-8")


def property_rows(text):
    for line in text.splitlines():
        line = line.split("#", 1)[0].strip()
        if line:
            yield [field.strip() for field in line.split(";")]


def ranges(values):
    result = []
    for codepoint, value in sorted(values.items()):
        if result and result[-1][1] + 1 == codepoint and result[-1][2] == value:
            result[-1] = (result[-1][0], codepoint, value)
        else:
            result.append((codepoint, codepoint, value))
    return result


def generate(mirroring, shaping, unicode_data):
    mirrors = [(int(row[0], 16), int(row[1], 16)) for row in property_rows(mirroring)]
    nonspacing = {}
    joining = {}
    forms = {}
    form_indexes = {"<isolated>": 0, "<final>": 1, "<initial>": 2, "<medial>": 3}
    for row in property_rows(unicode_data):
        codepoint = int(row[0], 16)
        if codepoint > 0xFFFF:
            continue
        if row[2] in ("Mn", "Me"):
            nonspacing[codepoint] = 1
        # UCD Joining_Type defaults: Mn, Me and Cf are transparent unless
        # ArabicShaping.txt explicitly supplies a different value.
        if row[2] in ("Mn", "Me", "Cf"):
            joining[codepoint] = 4
        decomposition = row[5].split()
        if len(decomposition) == 2 and decomposition[0] in form_indexes:
            base = int(decomposition[1], 16)
            forms.setdefault(base, [base] * 4)[form_indexes[decomposition[0]]] = codepoint
    for row in property_rows(shaping):
        codepoint = int(row[0], 16)
        if codepoint <= 0xFFFF:
            value = {"U": 0, "L": 1, "R": 2, "D": 3, "C": 3, "T": 4}[row[2]]
            if value:
                joining[codepoint] = value
            else:
                joining.pop(codepoint, None)
    lines = [
        "// Generated by tools/build_text_layout_data.py from Unicode 17.0.0.",
        "// Unicode data license: legal/Unicode-3.0.txt; pinned sources: legal/sources.json.",
        "",
        "pub(super) const MIRRORS: &[(u16, u16)] = &[",
    ]
    for source, target in sorted(mirrors):
        if source <= 0xFFFF and target <= 0xFFFF:
            lines.append(f"    (0x{source:04x}, 0x{target:04x}),")
    lines.extend([
        "];", "", "pub(super) const NONSPACING: &[(u16, u16)] = &[",
    ])
    for start, end, _ in ranges(nonspacing):
        lines.append(f"    (0x{start:04x}, 0x{end:04x}),")
    lines.extend([
        "];", "", "// Bits: joins next = 1, joins previous = 2, transparent = 4.",
        "pub(super) const JOINING: &[(u16, u16, u8)] = &[",
    ])
    for start, end, value in ranges(joining):
        lines.append(f"    (0x{start:04x}, 0x{end:04x}, {value}),")
    lines.extend([
        "];", "", "// Forms: isolated, final, initial, medial.",
        "pub(super) const ARABIC_FORMS: &[(u16, [u16; 4])] = &[",
    ])
    for base, variants in sorted(forms.items()):
        entries = ", ".join(f"0x{value:04x}" for value in variants)
        lines.append(f"    (0x{base:04x}, [{entries}]),")
    lines.extend(["];", ""])
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("mirroring", type=Path)
    parser.add_argument("shaping", type=Path)
    parser.add_argument("unicode_data", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    generated = generate(
        read_verified(args.mirroring, "BidiMirroring.txt"),
        read_verified(args.shaping, "ArabicShaping.txt"),
        read_verified(args.unicode_data, "UnicodeData.txt"),
    )
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(generated, encoding="utf-8")


if __name__ == "__main__":
    main()
